const {contextBridge, ipcRenderer} = require('electron');

contextBridge.exposeInMainWorld('electronAPI', {
    parsePhotoMetadata: (args) => ipcRenderer.invoke('photo:parse-metadata', args),
    watchImportImages: (callback) => ipcRenderer.on('images:watch-import', callback),
    watchImportFonts: (callback) => ipcRenderer.on('fonts:watch-import', callback),
    watchResources: (callback) => ipcRenderer.on('resources:watch-change', callback),
    openContextMenu: (args) => ipcRenderer.send('contextMenu:open', args),
    openTemplateContextMenu: () => ipcRenderer.send('template-contextMenu:open'),
    watchContextMenu: (callback) => ipcRenderer.on('contextMenu:watch', callback),
    watchTemplateContextMenu: (callback) => ipcRenderer.on('template-contextMenu:watch', callback),
    requestExportFiles: (args) => ipcRenderer.send('files:request-export', args),
    stopExportFiles: () => ipcRenderer.send('files:stop-export'),
    createThreadPool: (args) => ipcRenderer.send('thread-pool:create', args),
    requestImportFiles: (args) => ipcRenderer.send('files:request-import', args),
    setTheme: (theme) => ipcRenderer.send('theme:set', theme),
    watchDownloadProgress: (callback) => ipcRenderer.on('download-progress:watch', callback),
    openSettingsDialog: (callback) => ipcRenderer.on('settings-dialog:open', callback),
    openAboutDialog: (callback) => ipcRenderer.on('about-dialog:open', callback),
    watchTemplates: (callback) => ipcRenderer.on('templates:watch', callback),
    exportTemplates: (args) => ipcRenderer.send('templates:export', args),
    watchProjectSettings: (callback) => ipcRenderer.on('settings:watch', callback),
    exportSettings: (args) => ipcRenderer.send('settings:export', args),
    deleteImages: (args) => ipcRenderer.send('images:delete', args),
    requestImportBackgroundImage: (args) => ipcRenderer.send('image:request-import', args),
    watchImportBackgroundImage: (callback) => ipcRenderer.on('image:watch-import', callback),
    // 图片管理器（独立窗口，画布数据经主进程中转）
    imageManagerRequestData: () => ipcRenderer.send('image-manager:request-data'),
    imageManagerWatchData: (callback) => ipcRenderer.on('image-manager:data', callback),
    imageManagerSync: (args) => ipcRenderer.send('image-manager:sync', args),
    watchImageManagerCollect: (callback) => ipcRenderer.on('image-manager:collect', callback),
    watchImageManagerRemoveApply: (callback) => ipcRenderer.on('image-manager:apply-remove', callback),
    watchImageManagerMoved: (callback) => ipcRenderer.on('image-manager:moved', callback),
    imageManagerRemove: (args) => ipcRenderer.send('image-manager:remove', args),
    imageManagerDelete: (args) => ipcRenderer.send('image-manager:delete', args),
    imageManagerMove: (args) => ipcRenderer.send('image-manager:move', args),
    watchImageManagerMoveResult: (callback) => ipcRenderer.on('image-manager:move-result', callback),
    watchThemeChanged: (callback) => ipcRenderer.on('theme:changed', callback),

    // 语言切换（渲染进程为设置来源，主进程持久化并重建原生 UI 后广播回各窗口）
    setLanguage: (language) => ipcRenderer.send('language:set', language),
    watchLanguageChanged: (callback) => ipcRenderer.on('language:changed', callback),
});
